export function isPatchRequired(followerA: string, followerB: string): boolean {
  return (
    patchPairsSet.has(`${followerA}|${followerB}`) ||
    patchPairsSet.has(`${followerB}|${followerA}`)
  );
}

// Group tag definitions for Skyrim mod packs
export const SUPER_NPC_SET = new Set([
  'Amalee', 'Anum-La', 'Zora Fair-Child', 'Rumarin', 'Gorr', 'Skjarn', 'Valgus', 'Isobel', 'Tikrid', 'Froa', 'Daenlyn'
]);

export const ANNA_NPC_SET = new Set([
  'Anduniel', 'Darion', 'Elyndra', 'Garrett', 'Lyra', 'Mareen', 'Nadina', 'Teryn', 'Valyen', 'Zorya'
]);

export const KWF_NPC_SET = new Set([
  'Bikhai', "Ma'kara", 'Nanak', "S'ariq"
]);

export function getModPackTag(name: string, mod: string): { label: string; styleClass: string } | null {
  if (ANNA_NPC_SET.has(name)) {
    return {
      label: 'Anna NPCs',
      styleClass: 'bg-indigo-950/40 text-indigo-300 border border-indigo-800/60'
    };
  }
  if (KWF_NPC_SET.has(name)) {
    return {
      label: 'Khajiit Will Follow',
      styleClass: 'bg-amber-950/40 text-amber-300 border border-amber-800/60'
    };
  }
  if (mod === 'Interesting NPCs (3DNPC)') {
    if (SUPER_NPC_SET.has(name)) {
      return {
        label: '3DNPC Super',
        styleClass: 'bg-emerald-950/40 text-emerald-300 border border-emerald-800/60'
      };
    }
    return {
      label: '3DNPC',
      styleClass: 'bg-teal-950/40 text-teal-300 border border-teal-800/50'
    };
  }
  return null;
}
